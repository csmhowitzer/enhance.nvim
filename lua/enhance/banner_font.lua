-- Small five-row block alphabet for database names in the dashboard header.
local M = {}

-- Five columns per glyph, with rows separated by '/'.
local glyphs = {
  A = '01110/10001/11111/10001/10001', B = '11110/10001/11110/10001/11110',
  C = '01111/10000/10000/10000/01111', D = '11110/10001/10001/10001/11110',
  E = '11111/10000/11110/10000/11111', F = '11111/10000/11110/10000/10000',
  G = '01111/10000/10111/10001/01111', H = '10001/10001/11111/10001/10001',
  I = '11111/00100/00100/00100/11111', J = '00111/00010/00010/10010/01100',
  K = '10001/10010/11100/10010/10001', L = '10000/10000/10000/10000/11111',
  M = '10001/11011/10101/10001/10001', N = '10001/11001/10101/10011/10001',
  O = '01110/10001/10001/10001/01110', P = '11110/10001/11110/10000/10000',
  Q = '01110/10001/10001/10011/01111', R = '11110/10001/11110/10010/10001',
  S = '01111/10000/01110/00001/11110', T = '11111/00100/00100/00100/00100',
  U = '10001/10001/10001/10001/01110', V = '10001/10001/10001/01010/00100',
  W = '10001/10001/10101/10101/01010', X = '10001/01010/00100/01010/10001',
  Y = '10001/01010/00100/00100/00100', Z = '11111/00010/00100/01000/11111',
  ['0'] = '01110/10011/10101/11001/01110', ['1'] = '00100/01100/00100/00100/01110',
  ['2'] = '11110/00001/01110/10000/11111', ['3'] = '11110/00001/01110/00001/11110',
  ['4'] = '10010/10010/11111/00010/00010', ['5'] = '11111/10000/11110/00001/11110',
  ['6'] = '01111/10000/11110/10001/01110', ['7'] = '11111/00010/00100/01000/01000',
  ['8'] = '01110/10001/01110/10001/01110', ['9'] = '01110/10001/01111/00001/11110',
  ['_'] = '00000/00000/00000/00000/11111', ['.'] = '00000/00000/00000/00000/00100',
  ['-'] = '00000/00000/11111/00000/00000', [' '] = '00000/00000/00000/00000/00000',
  ['?'] = '11110/00001/00110/00000/00100',
}

---Spell a database name in block letters; wrap at glyph boundaries.
---@param name string
---@param width integer Available display cells (including the left margin)
---@return string[] banner
function M.render(name, width)
  local letters = {}
  name = tostring(name):upper()
  for i = 0, vim.fn.strchars(name) - 1 do
    letters[#letters + 1] = vim.fn.strcharpart(name, i, 1)
  end
  local per_line = math.max(1, math.floor((width - 3) / 6))
  local banner = {}
  for start = 1, #letters, per_line do
    for row = 1, 5 do
      local parts = {}
      for i = start, math.min(start + per_line - 1, #letters) do
        local glyph = glyphs[letters[i]] or glyphs['?']
        parts[#parts + 1] = glyph:sub((row - 1) * 6 + 1, (row - 1) * 6 + 5)
          :gsub('1', '█'):gsub('0', ' ')
      end
      banner[#banner + 1] = table.concat(parts, ' ')
    end
    if start + per_line <= #letters then banner[#banner + 1] = '' end
  end
  return banner
end

return M
